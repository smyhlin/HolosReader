internal fun ordinalWord(
    value: Long,
    case: Case,
    gender: Gender,
    number: NumberForm,
    animacy: Animacy,
    variant: Variant,
): String {
    val plural = number == NumberForm.PLURAL
    val form = if (plural) 3 else gender.ordinal
    val nounCase = if (case == ACCUSATIVE && animacy == Animacy.ANIMATE && (plural || gender == Gender.MASCULINE)) {
        GENITIVE
    } else {
        case
    }
    return when (value) {
        0L -> zeroForms[form][nounCase, variant]
        3L -> thirdForms[form][nounCase, variant]
        else -> ordinalStems.getValue(value) + hardEndings[form][nounCase, variant]
    }
}
