// Lexical forms and stress marks adapted from yar-numerals 1.0.8.
// See licenses/yar-numerals.txt for the upstream license.
internal class Forms(row: String) {
    private val cases = row.split(' ').map { it.split('/') }

    operator fun get(case: Case, variant: Variant): String {
        val forms = cases[case.ordinal]
        return if (variant == Variant.ALTERNATIVE) forms.last() else forms.first()
    }
}

