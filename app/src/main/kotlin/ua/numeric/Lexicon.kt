    "одне́/одно́ одного́ одному́ одне́ одни́м одному́/одні́м",
)
private val twoFeminine = Forms(
    "дві́ дво́х дво́м дві́ двома́ дво́х",
)

internal fun cardinalWord(value: Int, case: Case, gender: Gender, animacy: Animacy, variant: Variant): String {
    val forms = when {
        value == 1 && gender == Gender.FEMININE -> oneFeminine
        value == 1 && gender == Gender.NEUTER -> oneNeuter
        value == 2 && gender == Gender.FEMININE -> twoFeminine
        else -> cardinalForms.getValue(value)
    }
    if (case == ACCUSATIVE && animacy == Animacy.ANIMATE) {
        if (value == 1 && gender == Gender.MASCULINE) return forms[GENITIVE, variant]
        if (value in 2..4) return forms[GENITIVE, variant]
        val alternatives = forms[GENITIVE, Variant.ALTERNATIVE]
        // The productive animate forms for 5–99 end in -ох.
        if (value in 5..99 && alternatives.endsWith("о́х")) return alternatives
    }
    return forms[case, variant]
}

